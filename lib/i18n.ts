const unitKeys: Record<string, string> = {
  heure: "unit.hour",
  "demi-journée": "unit.halfday",
  journée: "unit.day",
  forfait: "unit.package",
};

export function translate(locale: Locale, key: string) {
  return messages[locale][key] ?? messages.fr[key] ?? key;
}

export function translateCategory(locale: Locale, category: string) {
  return translate(locale, categoryKeys[category] || category);
}

export function translateUnit(locale: Locale, unit: string) {
  return translate(locale, unitKeys[unit] || unit);
}

export function translateAdminError(locale: Locale, message: string) {
  const rules: [string, string][] = [
    ["Ce slug est déjà utilisé", "slugExists"],
    ["La capacité minimale", "capacity"],
    ["Une nouvelle image principale", "primaryRequired"],
    ["Ajoutez une image principale", "primaryMissing"],
    ["dépasse la taille maximale", "fileTooLarge"],
    ["doit faire moins de", "fileTooLarge"],
    ["Formats acceptés", "format"],
    ["La galerie est limitée", "galleryLimit"],
    ["La galerie contient", "imageReference"],
    ["Les références d’image", "imageChanged"],
    ["Le stockage Cloudinary", "cloudinary"],
    ["Cloudinary is not configured", "cloudinary"],
    ["Cloudinary n’a pas pu téléverser", "cloudinaryUpload"],
    ["Cloudinary a refusé le téléversement", "cloudinaryRejected"],
    ["Espace introuvable", "notFound"],
    ["L’espace a été enregistré", "cleanup"],
  ];
  const match = rules.find(([prefix]) => message.startsWith(prefix));
  return match ? translate(locale, `admin.error.${match[1]}`) : message;
}

export function localizeSpace(space: Space, locale: Locale): Space {
  if (locale === "fr") return space;
  const translation = space.translations?.[locale];
  return {
    ...space,
    name: translation?.name || space.name,
    description: translation?.description || space.description,
    amenities: translation?.amenities?.length ? translation.amenities : space.amenities,
    services: translation?.services?.length ? translation.services : space.services,
  };
}
